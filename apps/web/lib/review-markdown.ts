import type { PullRequestRow, Review } from "@/lib/api";

/** Where a finding's lines are on GitHub, at the reviewed commit when known. */
export function findingLink(
  row: Pick<PullRequestRow, "html_url" | "number">,
  review: Pick<Review, "head_sha">,
  file: string,
  startLine: number,
  endLine: number,
): string {
  const repoUrl = row.html_url.replace(/\/pull\/\d+$/, "");
  const ref = review.head_sha ?? "HEAD";
  const path = file.split("/").map(encodeURIComponent).join("/");
  const anchor = startLine > 0 ? `#L${startLine}${endLine > startLine ? `-L${endLine}` : ""}` : "";
  return `${repoUrl}/blob/${ref}/${path}${anchor}`;
}

/** A review as Markdown you can paste into a GitHub comment. Dismissed findings are left out. */
export function reviewToMarkdown(row: PullRequestRow, review: Review): string {
  const open = review.findings.filter((f) => f.status === "open");
  const lines: string[] = [
    `## Review of ${row.repository}#${row.number}: ${row.title}`,
    "",
    `**Risk:** ${review.risk ?? "unknown"} · **Findings:** ${open.length}`,
    "",
    review.summary ?? "",
  ];
  if (review.notes) lines.push("", `_${review.notes}_`);
  for (const f of open) {
    const where =
      f.start_line > 0
        ? `${f.file}:${f.start_line}${f.end_line > f.start_line ? `-${f.end_line}` : ""}`
        : f.file;
    const link = findingLink(row, review, f.file, f.start_line, f.end_line);
    const origin = f.origin === "scan" ? " · found by the credential scanner" : "";
    lines.push(
      "",
      `### [${f.severity.toUpperCase()}] ${f.title}`,
      `[${where}](${link}) · ${f.category} · confidence ${f.confidence}${origin}`,
      "",
      f.explanation,
    );
    if (f.suggestion) lines.push("", `**Suggestion:** ${f.suggestion}`);
  }
  lines.push("", "_Generated by DevPilot AI. AI can be wrong: check each finding before acting on it._");
  return lines.join("\n");
}
