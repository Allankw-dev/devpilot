import type { CiAnalysis, CiCategory, CiRunRow } from "@/lib/api";

export const CATEGORY_LABEL: Record<CiCategory, string> = {
  test_failure: "Test failure",
  build_error: "Build error",
  lint_or_types: "Lint or types",
  dependency: "Dependencies",
  configuration: "Configuration",
  infrastructure: "Infrastructure",
  flaky_or_timeout: "Timeout or flaky",
  unknown: "Unclear",
};

/** An analysis as Markdown you can paste into an issue or a chat. Quotes go in code blocks. */
export function analysisToMarkdown(run: CiRunRow, a: CiAnalysis): string {
  const lines: string[] = [
    `## Why ${run.repository} "${run.name ?? "CI"}" #${run.run_number ?? "?"} failed`,
    "",
    `**Type:** ${a.category ? CATEGORY_LABEL[a.category] : "unknown"} · **Confidence:** ${a.confidence ?? "unknown"}`,
    "",
    a.summary ?? "",
  ];
  if (a.likely_cause) lines.push("", `**Likely cause:** ${a.likely_cause}`);
  if (a.suggested_fix) lines.push("", `**Suggested fix:** ${a.suggested_fix}`);
  if (a.failed_steps.length > 0) {
    lines.push("", "**Failed steps:**");
    for (const s of a.failed_steps) lines.push(`- ${s.job}${s.step ? `: ${s.step}` : ""}`);
  }
  for (const e of a.evidence) lines.push("", `From the log of \`${e.job}\`:`, "```", e.quote, "```");
  if (a.notes) lines.push("", `_${a.notes}_`);
  lines.push("", "_Generated by DevPilot AI. AI can be wrong: check the log before acting on this._");
  return lines.join("\n");
}
